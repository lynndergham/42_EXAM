#include <unistd.h>

int main(int ac, char **av)
{
    if (ac == 2)
    {
        int i = 0;
        char c;

        while (av[1][i])
        {
            if (i != 0 && av[1][i] >= 'A' && av[1][i] <= 'Z')
            {
                c = av[1][i] + 32;
                write(1, "_", 1);
                write(1, &c, 1);
            }
            else
                write(1, &av[1][i], 1);
            i++;
        }
        
    }
    write(1, "\n", 1);
}